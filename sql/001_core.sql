-- Bootstrap scaffold: run in an explicitly selected isolated database/schema.
-- Not executed against Snowflake. Grants, row access policies, Search, semantic
-- views, agent objects, and loading are follow-up CoCo tasks.
-- Single synthetic traveler only until isolation is implemented and verified.
-- Missing migrations include inventory, payment/benefit metadata, reminders and
-- supporting panels. Control-store DDL is separate (planned SQLite).
-- IF NOT EXISTS is bootstrap behavior, not a schema upgrade mechanism.
-- UTC instants alone do not preserve regional DST rules: retain IANA zones.
CREATE TABLE IF NOT EXISTS ITINERARIES (
  ITINERARY_ID VARCHAR NOT NULL,
  OWNER_ID VARCHAR NOT NULL,
  TITLE VARCHAR,
  REVISION NUMBER DEFAULT 1,
  PREFERENCES VARIANT,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS TRIP_DOCUMENTS (
  DOCUMENT_ID VARCHAR NOT NULL,
  ITINERARY_ID VARCHAR NOT NULL,
  STORAGE_REFERENCE VARCHAR,
  CONTENT_HASH VARCHAR,
  MIME_TYPE VARCHAR,
  PARSE_STATE VARCHAR,
  SENSITIVITY VARCHAR,
  UPLOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS BOOKINGS (
  BOOKING_ID VARCHAR NOT NULL,
  ITINERARY_ID VARCHAR NOT NULL,
  BOOKING_TYPE VARCHAR,
  PROVIDER VARCHAR,
  START_AT TIMESTAMP_TZ,
  END_AT TIMESTAMP_TZ,
  LOCAL_TIMEZONE VARCHAR,
  STATUS VARCHAR,
  FACTS VARIANT,
  SOURCE_DOCUMENT_ID VARCHAR
);

CREATE TABLE IF NOT EXISTS BOOKING_DEPENDENCIES (
  ITINERARY_ID VARCHAR NOT NULL,
  PREDECESSOR_ID VARCHAR NOT NULL,
  SUCCESSOR_ID VARCHAR NOT NULL,
  MINIMUM_TRANSFER_MINUTES NUMBER,
  SOURCE_DOCUMENT_ID VARCHAR
);

CREATE TABLE IF NOT EXISTS TRIP_COMMITMENTS (
  COMMITMENT_ID VARCHAR NOT NULL,
  ITINERARY_ID VARCHAR NOT NULL,
  TITLE VARCHAR NOT NULL,
  COMMITMENT_TYPE VARCHAR,
  START_AT TIMESTAMP_TZ NOT NULL,
  END_AT TIMESTAMP_TZ,
  LOCATION VARCHAR,
  FLEXIBILITY VARCHAR,
  SOURCE VARCHAR,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS COMMITMENT_IMPACTS (
  ITINERARY_ID VARCHAR NOT NULL,
  COMMITMENT_ID VARCHAR NOT NULL,
  EVENT_ID VARCHAR NOT NULL,
  STATUS VARCHAR NOT NULL,
  REASON VARCHAR,
  SUGGESTED_ACTION VARCHAR,
  CALCULATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS DOCUMENT_CHUNKS (
  CHUNK_ID VARCHAR NOT NULL,
  ITINERARY_ID VARCHAR NOT NULL,
  DOCUMENT_ID VARCHAR NOT NULL,
  PAGE_NUMBER NUMBER,
  CHUNK_TEXT VARCHAR,
  POLICY_VERSION VARCHAR
);

CREATE TABLE IF NOT EXISTS FLIGHT_EVENTS (
  EVENT_ID VARCHAR NOT NULL,
  ITINERARY_ID VARCHAR NOT NULL,
  PROVIDER VARCHAR,
  OBSERVED_AT TIMESTAMP_TZ,
  RECEIVED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  PAYLOAD VARIANT,
  IS_SIMULATED BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS RECOVERY_PLANS (
  PLAN_ID VARCHAR NOT NULL,
  ITINERARY_ID VARCHAR NOT NULL,
  EVENT_ID VARCHAR NOT NULL,
  ITINERARY_REVISION NUMBER,
  PLAN VARIANT,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RECOVERY_ACTIONS (
  ACTION_ID VARCHAR NOT NULL,
  ITINERARY_ID VARCHAR NOT NULL,
  PLAN_ID VARCHAR NOT NULL,
  IDEMPOTENCY_KEY VARCHAR NOT NULL,
  STATUS VARCHAR,
  APPROVED_AT TIMESTAMP_TZ,
  RESULT VARIANT
);

-- Snowflake standard-table uniqueness/FK constraints are not an idempotency
-- mechanism. Backend coordination must enforce unique events and actions.
-- The 15-document limit also requires concurrency-safe backend enforcement.
